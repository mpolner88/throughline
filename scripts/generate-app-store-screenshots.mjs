function main() {
  fs.mkdirSync(outputDir, { recursive: true });
  for (const file of fs.readdirSync(outputDir)) {
    if (file.endsWith(".png")) {
      fs.unlinkSync(path.join(outputDir, file));
    }
  }

  fs.writeFileSync(sourcePath, html(), "utf8");
  fs.writeFileSync(path.join(outputDir, "README.md"), readme(), "utf8");

  if (!fs.existsSync(chromePath)) {
    throw new Error(`Google Chrome not found at ${chromePath}`);
  }

  for (let index = 0; index < shots.length; index += 1) {
    const shot = shots[index];
    const outPath = path.join(outputDir, `${shot.slug}.png`);
    const url = `${pathToFileURL(sourcePath).href}?shot=${index}`;
    const result = spawnSync(chromePath, [
      "--headless=new",
      "--disable-gpu",
      "--hide-scrollbars",
      "--no-first-run",
      "--force-device-scale-factor=1",
      "--virtual-time-budget=1500",
      `--window-size=${width},${height}`,
      `--screenshot=${outPath}`,
      url,
    ], {
      cwd: root,
      encoding: "utf8",
      stdio: "pipe",
    });

    if (result.status !== 0) {
      throw new Error(`Chrome screenshot failed for ${shot.slug}\n${result.stderr || result.stdout}`);
    }

    console.log(`wrote ${path.relative(root, outPath)}`);
  }
}

