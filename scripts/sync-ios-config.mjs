import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const envPath = path.join(root, ".env.local");
const outputPath = path.join(root, "ios", "Config", "Local.xcconfig");
const releaseOutputPath = path.join(root, "ios", "Config", "LocalRelease.xcconfig");

function readEnvFile(filePath) {
  const values = new Map();
  const text = fs.readFileSync(filePath, "utf8");

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const index = line.indexOf("=");
    if (index === -1) continue;

    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values.set(key, value);
  }

  return values;
}

function hash(value) {
  return crypto.createHash("sha256").update(value).digest("hex").slice(0, 12);
}

function xcconfigValue(value) {
  return value.replaceAll("//", "/$()/");
}

if (!fs.existsSync(envPath)) {
  console.error(".env.local is missing; cannot sync iOS backend token.");
  process.exit(1);
}

const env = readEnvFile(envPath);
const token = env.get("THROUGHLINE_API_TOKEN")?.trim() || "";
const supabaseURL = env.get("SUPABASE_URL")?.trim() || "https://ywsenspsfyrdhgyxgcrv.supabase.co";
const supabaseAnonKey = env.get("SUPABASE_ANON_KEY")?.trim();

if (!supabaseAnonKey) {
  console.error("SUPABASE_ANON_KEY is missing from .env.local.");
  process.exit(1);
}

for (const [key, value] of [
  ["THROUGHLINE_API_TOKEN", token],
  ["SUPABASE_URL", supabaseURL],
  ["SUPABASE_ANON_KEY", supabaseAnonKey],
]) {
  if (/[\r\n]/.test(value)) {
    console.error(`${key} must be a single-line value.`);
    process.exit(1);
  }
}

if (!/^https:\/\/[^/]+\.supabase\.co$/.test(supabaseURL)) {
  console.error("SUPABASE_URL must be the project URL, for example https://project-ref.supabase.co.");
  process.exit(1);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  [
    "// Generated by npm run ios:sync-config. Do not commit.",
    `THROUGHLINE_API_TOKEN = ${token}`,
    `SUPABASE_URL = ${xcconfigValue(supabaseURL)}`,
    `SUPABASE_ANON_KEY = ${supabaseAnonKey}`,
    "",
  ].join("\n"),
);
fs.writeFileSync(
  releaseOutputPath,
  [
    "// Generated by npm run ios:sync-config. Do not commit.",
    "THROUGHLINE_API_TOKEN =",
    `SUPABASE_URL = ${xcconfigValue(supabaseURL)}`,
    `SUPABASE_ANON_KEY = ${supabaseAnonKey}`,
    "",
  ].join("\n"),
);

console.log([
  token
    ? `Synced debug backend token (${token.length} chars, sha256:${hash(token)}).`
    : "No debug backend token configured.",
  `Synced Supabase URL (${supabaseURL}).`,
  `Synced Supabase anon key (${supabaseAnonKey.length} chars, sha256:${hash(supabaseAnonKey)}).`,
  "Release config leaves THROUGHLINE_API_TOKEN empty.",
].join(" "));
